#!/usr/bin/env python3
"""
Transform the v1 data export (migration-import.sql) into SQL for the v2 schema.

Usage:
    python3 scripts/transform-v1-data.py OLD_SCHEMA.sql migration-import.sql OWNER_EMAIL > scripts/seed-v2.sql

OLD_SCHEMA.sql is the v1 table definitions (git show <v1-commit>:apps/worker/src/db/migrations/0000_panoramic_firebird.sql).

The output creates one farm owned by OWNER_EMAIL. The owner's user row has no Google id yet;
it is linked on their first Google sign-in with that (verified) address.
Animal ids are preserved so dam links stay intact.
"""
import sqlite3
import sys
from datetime import date

BREEDS = {
    'char': 'Charolais', 'ch': 'Charolais',
    'lim': 'Limousin',
    'sim': 'Simmental', 'simm': 'Simmental',
    'aa': 'Aberdeen Angus',
    'luing': 'Luing',
}


def breed(value):
    if not value:
        return None
    return BREEDS.get(value.strip().lower(), value.strip())


def sex(value):
    v = (value or '').strip().lower()
    if v.startswith('male'):
        return 'male'
    if v.startswith(('fem', 'hief', 'heif')):
        return 'female'
    return None


def q(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return '1' if value else '0'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(table, row):
    cols = ', '.join(row.keys())
    vals = ', '.join(q(v) for v in row.values())
    return f'INSERT INTO {table} ({cols}) VALUES ({vals});'


def days_between(a, b):
    return abs((date.fromisoformat(a) - date.fromisoformat(b)).days)


def main():
    schema_path, dump_path, owner_email = sys.argv[1], sys.argv[2], sys.argv[3].strip().lower()
    old = sqlite3.connect(':memory:')
    old.row_factory = sqlite3.Row
    old.executescript(open(schema_path).read())
    old.executescript(open(dump_path).read())

    out = [
        '-- v2 seed generated by scripts/transform-v1-data.py from the 2026-01-10 v1 export',
        'PRAGMA defer_foreign_keys = ON;',
        insert('users', {'id': 1, 'email': owner_email, 'name': None}),
        insert('farms', {'id': 1, 'name': 'Home Farm', 'slug': 'home-farm', 'currency': 'GBP',
                         'area_unit': 'ha', 'species': '["cattle"]'}),
        insert('farm_members', {'farm_id': 1, 'user_id': 1, 'role': 'owner'}),
        'UPDATE users SET last_farm_id = 1 WHERE id = 1;',
    ]

    cattle = old.execute('SELECT * FROM cattle ORDER BY id').fetchall()
    by_id = {c['id']: c for c in cattle}
    # Insert dams before their offspring so foreign keys hold without deferral.
    ordered, placed = [], set()
    def place(c):
        if c['id'] in placed:
            return
        dam = by_id.get(c['dam_tag'])
        if dam and dam['id'] != c['id']:
            place(dam)
        placed.add(c['id'])
        ordered.append(c)
    for c in cattle:
        place(c)
    for c in ordered:
        notes = c['notes']
        if notes and notes.strip().lower().startswith('feet trimming'):
            notes = None  # carried as a health record instead
        elif notes and notes.startswith('Sale/Death note: '):
            notes = notes[len('Sale/Death note: '):]
        out.append(insert('animals', {
            'id': c['id'], 'farm_id': 1, 'species': 'cattle',
            'tag_no': c['tag_no'].strip(), 'management_tag': c['management_tag'],
            'sex': sex(c['sex']) or 'female', 'castrated': 0,
            'breed': breed(c['breed']), 'dob': c['dob'], 'birth_year': c['yob'],
            'dam_id': c['dam_tag'] if c['dam_tag'] in by_id else None,
            'size': c['size'], 'status': 'active', 'origin': 'born', 'notes': notes,
        }))

    # Births: link to the calf whose dam matches and DOB is within 3 days of the calving date.
    births = old.execute('SELECT * FROM calving_events ORDER BY calving_date, id').fetchall()
    claimed = set()
    birth_by_dam = {}
    for b in births:
        # v1 import bug: calving_events.mother_id often points at the cow's *latest calf*, not the
        # cow. An "mother" too young to have calved (< ~20 months at the calving date) is a calf;
        # the real dam is that calf's dam.
        dam_id = b['mother_id']
        recorded = by_id.get(dam_id)
        if (recorded and recorded['dam_tag'] in by_id
                and (date.fromisoformat(b['calving_date']) - date.fromisoformat(recorded['dob'])).days < 600):
            dam_id = recorded['dam_tag']
        raw = (b['calf_sex'] or '').strip()
        lower = raw.lower()
        outcome = 'alive'
        if 'doa' in lower or 'stillborn' in lower:
            outcome = 'stillborn'
        elif 'died' in lower:
            outcome = 'died'
        offspring = None
        if outcome == 'alive':
            for c in cattle:
                if (c['dam_tag'] == dam_id and c['id'] not in claimed and c['dob']
                        and days_between(c['dob'], b['calving_date']) <= 3):
                    offspring = c['id']
                    claimed.add(c['id'])
                    break
        notes = b['notes']
        if raw and lower not in ('male', 'female'):
            notes = '; '.join(filter(None, [notes, f'Recorded as: {raw}']))
        out.append(insert('birth_records', {
            'farm_id': 1, 'dam_id': dam_id, 'offspring_id': offspring,
            'date': b['calving_date'],
            'sex': sex(raw) or (sex(by_id[offspring]['sex']) if offspring else None),
            'sire_name': breed(b['sire']), 'outcome': outcome, 'notes': notes,
        }))
        birth_by_dam.setdefault(dam_id, []).append(b['calving_date'])

    for s in old.execute('SELECT * FROM service_events ORDER BY service_date, id').fetchall():
        # Same v1 bug as calvings: cow_id can point at the cow's latest calf (too young to be served).
        cow_id = s['cow_id']
        recorded = by_id.get(cow_id)
        if (recorded and recorded['dam_tag'] in by_id
                and (date.fromisoformat(s['service_date']) - date.fromisoformat(recorded['dob'])).days < 300):
            cow_id = recorded['dam_tag']
        outcome = 'pending'
        expected = s['expected_calving_date']
        if expected and any(days_between(d, expected) <= 45 for d in birth_by_dam.get(cow_id, [])):
            outcome = 'born'
        out.append(insert('breeding_records', {
            'farm_id': 1, 'animal_id': cow_id, 'event': 'service', 'date': s['service_date'],
            'method': 'natural', 'sire_name': breed(s['sire']), 'expected_due_date': expected,
            'outcome': outcome, 'notes': s['notes'],
        }))

    for h in old.execute('SELECT * FROM health_events ORDER BY event_date, id').fetchall():
        title = (h['event_type'] or 'Health event').strip()
        out.append(insert('health_records', {
            'farm_id': 1, 'animal_id': h['animal_id'], 'date': h['event_date'],
            'type': 'procedure' if 'feet' in title.lower() else 'observation',
            'title': title[:1].upper() + title[1:],
            'notes': None if (h['description'] or '').strip().lower() == 'yes' else h['description'],
        }))

    print('\n'.join(out))
    linked = len(claimed)
    print(f'-- animals={len(cattle)} births={len(births)} linked_births={linked}', file=sys.stderr)


if __name__ == '__main__':
    main()
